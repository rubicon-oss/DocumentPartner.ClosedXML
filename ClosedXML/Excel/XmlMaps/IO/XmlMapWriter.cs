using System;
using System.Linq;
using DocumentFormat.OpenXml.Packaging;
using DocumentFormat.OpenXml.Spreadsheet;
using static ClosedXML.Excel.XLWorkbook;

namespace ClosedXML.Excel.IO
{
    /// <summary>
    /// Writes XML maps (<c>xl/xmlMaps.xml</c>), mapped single cells (<c>tableSingleCells</c> parts) and
    /// XML properties of tables from the <see cref="XLXmlMapStore"/>. The parts are always regenerated,
    /// so the package never contains stale XML map data.
    /// </summary>
    internal static class XmlMapWriter
    {
        /// <summary>
        /// Add XML properties of a mapped table to a table element that was generated by <see cref="TablePartWriter"/>.
        /// </summary>
        internal static void ApplyTableBinding(TableDefinitionPart tableDefinitionPart, Table table, XLTable xlTable)
        {
            var store = xlTable.Worksheet.Workbook.XmlMapStoreOrNull;
            var binding = store?.GetTableBinding(xlTable);
            if (binding is null || table.TableColumns is null)
                return;

            var tableColumns = table.TableColumns.Elements<TableColumn>().ToList();
            var fieldNames = xlTable.Fields.OrderBy(f => f.Index).Select(f => f.Name).ToList();
            var matched = new bool[tableColumns.Count];
            var anyMatched = false;
            foreach (var columnBinding in binding.Columns)
            {
                var index = columnBinding.ResolveIndex(fieldNames);
                if (index < 0 || index >= tableColumns.Count || matched[index])
                    continue;

                var properties = (XmlColumnProperties)columnBinding.Properties.CloneNode(true);
                properties.MapId = columnBinding.Map.Id;
                tableColumns[index].UniqueName = columnBinding.UniqueName;
                tableColumns[index].XmlColumnProperties = properties;
                matched[index] = true;
                anyMatched = true;
            }

            if (!anyMatched)
                return;

            foreach (var (columnIndex, name, uniqueName) in binding.UnmappedColumns)
            {
                var index = XLXmlColumnBinding.ResolveIndex(name, columnIndex, fieldNames);
                if (index >= 0 && index < tableColumns.Count && !matched[index])
                    tableColumns[index].UniqueName = uniqueName;
            }

            var workbookPart = (tableDefinitionPart.OpenXmlPackage as SpreadsheetDocument)?.WorkbookPart;
            table.TableType = TableValues.Xml;
            if (binding.ConnectionId is { } connectionId && HasConnection(workbookPart, connectionId))
                table.ConnectionId = connectionId;

            if (binding.InsertRow is { } insertRow)
                table.InsertRow = insertRow;

            if (binding.InsertRowShift is { } insertRowShift)
                table.InsertRowShift = insertRowShift;

            if (binding.SortState is not null && table.SortState is null)
                table.SortState = (SortState)binding.SortState.CloneNode(true);
        }

        /// <summary>
        /// Write the <c>tableSingleCells</c> part of a worksheet. Must be called after the tables of the worksheet
        /// were written, because ids of mapped cells are taken from the same sequence as table ids.
        /// </summary>
        internal static void WriteCellBindings(WorksheetPart worksheetPart, XLWorksheet worksheet, SaveContext context)
        {
            var store = worksheet.Workbook.XmlMapStoreOrNull;
            if (store is null)
                return;

            var bindings = store.GetCellBindings(worksheet).ToList();
            if (bindings.Count == 0)
            {
                if (worksheetPart.SingleCellTablePart is not null)
                    worksheetPart.DeletePart(worksheetPart.SingleCellTablePart);

                return;
            }

            var workbookPart = (worksheetPart.OpenXmlPackage as SpreadsheetDocument)?.WorkbookPart;
            var singleXmlCells = new SingleXmlCells();
            foreach (var binding in bindings)
            {
                // Only known attributes are written, revision uids would need namespace declarations on the root.
                var xmlProperties = (XmlProperties?)binding.Properties.XmlProperties?.CloneNode(true) ?? new XmlProperties();
                xmlProperties.MapId = binding.Map.Id;
                var properties = new XmlCellProperties
                {
                    Id = 1,
                    UniqueName = binding.Properties.UniqueName?.Value,
                    XmlProperties = xmlProperties,
                };
                if (binding.Properties.ExtensionList is not null)
                    properties.ExtensionList = (ExtensionList)binding.Properties.ExtensionList.CloneNode(true);

                singleXmlCells.AppendChild(new SingleXmlCell
                {
                    Id = ++context.TableId,
                    CellReference = binding.Cell.RangeAddress.FirstAddress.ToStringRelative(),
                    ConnectionId = HasConnection(workbookPart, binding.ConnectionId) ? binding.ConnectionId : 0,
                    XmlCellProperties = properties,
                });
            }

            var part = worksheetPart.SingleCellTablePart ??
                       worksheetPart.AddNewPart<SingleCellTablePart>(context.RelIdGenerator.GetNext(RelType.Workbook));
            part.SingleXmlCells = singleXmlCells;
        }

        /// <summary>
        /// Write the XML maps part of the workbook or delete it, if there are no maps.
        /// </summary>
        internal static void WriteMaps(WorkbookPart workbookPart, XLWorkbook workbook, SaveContext context)
        {
            var store = workbook.XmlMapStoreOrNull;
            if (store is null)
                return;

            store.RemoveDeadBindings();
            if (store.MapList.Count == 0)
            {
                if (workbookPart.CustomXmlMappingsPart is not null)
                    workbookPart.DeletePart(workbookPart.CustomXmlMappingsPart);

                return;
            }

            var part = workbookPart.CustomXmlMappingsPart ??
                       workbookPart.AddNewPart<CustomXmlMappingsPart>(context.RelIdGenerator.GetNext(RelType.Workbook));
            XmlMapPartXml.Write(store, part, id => HasConnection(workbookPart, id));
        }

        private static bool HasConnection(WorkbookPart? workbookPart, uint connectionId)
        {
            return connectionId != 0 &&
                   workbookPart?.ConnectionsPart?.Connections?.Elements<Connection>().Any(c => c.Id?.Value == connectionId) == true;
        }
    }
}
